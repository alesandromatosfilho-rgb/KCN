function normTel(s) {
  if (!s) return '';
  let t = s.replace(/\s+/g, ' ').trim();
  t = t.replace(/\(\s*\)/g, '').replace(/\(00\)/g, '(88)');
  return t;
}

function parseLine(line) {
  line = line.trim();
  if (!line) return null;
  const m = line.match(/^(\d+)\s+(.+)$/);
  if (!m) return null;
  const cod = m[1];
  let rest = m[2];
  const phoneRe = /\((\d{2})\)\s*([\d\s\-]+)$/;
  const pm = rest.match(phoneRe);
  let telefone = '';
  let middle = rest;
  if (pm) {
    telefone = normTel(`(${pm[1]}) ${pm[2].replace(/\s+/g, '').replace(/(\d{4,5})(\d{4})$/, '$1-$2')}`);
    middle = rest.slice(0, rest.length - pm[0].length).trim();
  }
  const cnpjM = middle.match(/\b(\d{14})\b/);
  let cnpj = '';
  if (cnpjM) {
    cnpj = cnpjM[1];
    middle = middle.replace(cnpjM[0], '').replace(/\s+/g, ' ').trim();
  }
  const razao = middle.replace(/\s+/g, ' ').trim() || `Cliente ${cod}`;
  return {
    codigo_origem: cod,
    razao_social: razao.slice(0, 500),
    nome_fantasia: '',
    cnpj_cpf: cnpj || '',
    telefone: telefone || '',
    empresa: 'acp',
  };
}

